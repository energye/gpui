//go:build linux

package platform

// csdButtonState tracks interaction state for a title-bar control button.
type csdButtonState struct {
	Hovered bool
	Pressed bool
}

// csdState holds the current decoration state for painting.
type csdState struct {
	Title      string
	Focused    bool
	Maximized  bool
	Fullscreen bool
	// Locked = the window size is fixed (SetSize min==max clamp /
	// SetResizable(false)): resize grips and cursors are disabled.
	Locked bool
	// Tiled = xdg configure tiled state (screen-edge snap); informational
	// (GNOME still allows adjusting a tiled split via its edge).
	Tiled          bool
	Close          csdButtonState
	Maximize       csdButtonState
	Minimize       csdButtonState
	TitleAlignment int // 0 = center (default), 1 = left, 2 = right
}

// CSD geometry constants (logical px) — see design doc §4.
const (
	csdTitleBarHeight = 32
	csdBorderThick    = 4
	csdButtonW        = 44
	csdTitlePadLeft   = 12
	csdIconSize       = 10
	csdCornerGrip     = 8
)

// Embedded title font metrics (csdFont glyphs, 6x13 each). The system-font
// rasterizer (wayland_csd_font.go) renders at the same height so ASCII + CJK
// titles share one visual size.
const (
	csdBitmapGlyphW = 7
	csdBitmapGlyphH = 13
)

// CSD palette (ARGB8888 in memory: B,G,R,A).
var (
	csdColorBgFocus    = [4]byte{0x30, 0x2D, 0x2B, 0xFF} // #2B2D30
	csdColorBgUnfocus  = [4]byte{0x24, 0x22, 0x20, 0xFF} // #202224
	csdColorBorder     = [4]byte{0x34, 0x31, 0x2F, 0xFF} // unused border line color (frame line removed)
	csdColorBtnHover   = [4]byte{0x44, 0x41, 0x3E, 0xFF} // #3E4144
	csdColorBtnPress   = [4]byte{0x38, 0x35, 0x33, 0xFF} // #333538
	csdColorCloseHover = [4]byte{0x1C, 0x2B, 0xC4, 0xFF} // #C42B1C
	csdColorClosePress = [4]byte{0x1A, 0x2A, 0xB2, 0xFF} // #B22A1A
	csdColorIcon       = [4]byte{0xE5, 0xE1, 0xDF, 0xFF} // #DFE1E5
	csdColorIconClose  = [4]byte{0xFF, 0xFF, 0xFF, 0xFF}
)

// paintTitleBar renders the title bar into an ARGB8888 buffer (stride=w*4).
func paintTitleBar(buf []byte, w, h int, st csdState) {
	bg := csdColorBgFocus
	if !st.Focused {
		bg = csdColorBgUnfocus
	}
	fillRect(buf, w, 0, 0, w, h, bg)

	// The buttons are right-aligned; on a window narrower than all three
	// (interactive resize can configure down to ~1px) their left edge is
	// negative. Skip them entirely — the resize grips and caption drag are
	// hit-tested, not painted (putPxA also guards negative coords).
	if w < csdButtonW*3 {
		return
	}

	// Buttons right-aligned: [minimize] [maximize] [close]
	closeX := w - csdButtonW
	maxX := closeX - csdButtonW
	minX := maxX - csdButtonW

	paintButton(buf, w, minX, 0, csdButtonW, h, st.Minimize)
	drawMinimizeGlyph(buf, w, minX, 0, csdButtonW, h, csdColorIcon)

	paintButton(buf, w, maxX, 0, csdButtonW, h, st.Maximize)
	drawMaximizeGlyph(buf, w, maxX, 0, csdButtonW, h, csdColorIcon, st.Maximized)

	btnBg := csdColorCloseHover
	if st.Close.Pressed {
		btnBg = csdColorClosePress
	} else if !st.Close.Hovered {
		btnBg = csdColorBtnHover
	}
	if st.Close.Hovered || st.Close.Pressed {
		fillRect(buf, w, closeX, 0, csdButtonW, h, btnBg)
	}
	ic := csdColorIcon
	if st.Close.Hovered || st.Close.Pressed {
		ic = csdColorIconClose
	}
	drawCloseGlyph(buf, w, closeX, 0, csdButtonW, h, ic)

	// Title text (centered by default; falls back to left on narrow widths).
	drawTitleText(buf, w, h, st.Title, csdColorIcon, minX)
}

// paintButton fills a hover/press button background.
func paintButton(buf []byte, stride, x, y, w, h int, st csdButtonState) {
	switch {
	case st.Pressed:
		fillRect(buf, stride, x, y, w, h, csdColorBtnPress)
	case st.Hovered:
		fillRect(buf, stride, x, y, w, h, csdColorBtnHover)
	}
}

// paintBorder renders one border edge — fully transparent. The subsurface
// is kept (with an opaque shm buffer of the right size) so pointer
// hit-testing still sees the edge for interactive resize; nothing is drawn
// (GTK4 Adwaita has no 1px frame line around the window).
func paintBorder(buf []byte, w, h int) {
	clearRect(buf, w, 0, 0, w, h)
}

// --- glyph drawing (ARGB8888, stride = w*4) ---

// drawMinimizeGlyph: horizontal line (—).
func drawMinimizeGlyph(buf []byte, stride, bx, by, bw, bh int, c [4]byte) {
	cx := bx + bw/2
	cy := by + bh/2
	half := csdIconSize / 2
	for x := cx - half; x <= cx+half; x++ {
		putPx(buf, stride, x, cy, c[2], c[1], c[0])
	}
}

// drawMaximizeGlyph: square (maximize) or two squares (restore).
func drawMaximizeGlyph(buf []byte, stride, bx, by, bw, bh int, c [4]byte, maximized bool) {
	cx := bx + bw/2
	cy := by + bh/2
	half := csdIconSize / 2
	if maximized {
		// Restore: back square offset up-right + front square.
		off := 2
		for x := cx - half + off; x <= cx+half+off; x++ {
			putPx(buf, stride, x, cy-half-off, c[2], c[1], c[0])
			putPx(buf, stride, x, cy+half-off, c[2], c[1], c[0])
		}
		for y := cy - half - off; y <= cy+half-off; y++ {
			putPx(buf, stride, cx-half+off, y, c[2], c[1], c[0])
			putPx(buf, stride, cx+half+off, y, c[2], c[1], c[0])
		}
	}
	for x := cx - half; x <= cx+half; x++ {
		putPx(buf, stride, x, cy-half, c[2], c[1], c[0])
		putPx(buf, stride, x, cy+half, c[2], c[1], c[0])
	}
	for y := cy - half; y <= cy+half; y++ {
		putPx(buf, stride, cx-half, y, c[2], c[1], c[0])
		putPx(buf, stride, cx+half, y, c[2], c[1], c[0])
	}
}

// drawCloseGlyph: X shape.
func drawCloseGlyph(buf []byte, stride, bx, by, bw, bh int, c [4]byte) {
	cx := bx + bw/2
	cy := by + bh/2
	half := csdIconSize / 2
	for i := -half; i <= half; i++ {
		putPx(buf, stride, cx+i, cy+i, c[2], c[1], c[0])
		putPx(buf, stride, cx+i, cy-i, c[2], c[1], c[0])
		putPx(buf, stride, cx+i+1, cy+i, c[2], c[1], c[0])
		putPx(buf, stride, cx+i+1, cy-i, c[2], c[1], c[0])
	}
}

// drawTitleText renders the title: printable ASCII uses the embedded bitmap
// font; non-ASCII runes are rasterized from a system font (wayland_csd_font.go,
// e.g. Noto Sans CJK) and alpha-blended in. Widths are summed per rune so
// mixed ASCII + CJK titles center correctly.
func drawTitleText(buf []byte, stride, h int, text string, c [4]byte, minX int) {
	const padL = csdTitlePadLeft
	if text == "" {
		return
	}
	// Collect each rune's draw mode + pixel advance in one pass: bitmap glyphs
	// are fixed 7px, system glyphs use their advance (CJK ≈13px em). System
	// glyphs are rasterized here (and cached), so the paint pass below is a
	// pure table walk with no locks.
	type item struct {
		r   rune
		adv int
		g   csdGlyph
		ok  bool // g valid (system face rendered this rune)
	}
	items := make([]item, 0, len(text))
	var textW int
	for _, r := range text {
		it := item{r: r, adv: csdBitmapGlyphW}
		if !isCSDBitmapRune(r) {
			if g, ok := csdSysGlyph(r); ok {
				it.g, it.ok, it.adv = g, true, g.advance
			}
		}
		items = append(items, it)
		textW += it.adv
	}

	// x: center in the full width, fall back to left pad when it would
	// overlap the buttons.
	x := (stride - textW) / 2
	limit := minX - padL
	if x < padL || x+textW > limit {
		x = padL
	}
	yOff := (h - csdBitmapGlyphH) / 2
	if yOff < 0 {
		yOff = 0
	}

	// System glyphs are vertically centered in the same 13px slot as the
	// bitmap glyphs (yOff..yOff+glyphH), so ASCII + CJK align on one baseline
	// regardless of the face's metrics.
	cx := x
	for _, it := range items {
		if cx+it.adv > limit {
			break
		}
		switch {
		case isCSDBitmapRune(it.r):
			ch := byte(it.r)
			if it.r == '–' || it.r == '—' {
				ch = '-'
			}
			drawCSDBitmapGlyph(buf, stride, cx, yOff, h, ch, c)
		case it.ok:
			blendCSDGlyph(buf, stride, cx+it.g.dx, yOff+(csdBitmapGlyphH-it.g.height)/2, it.g, c)
		default:
			// No system face / missing glyph: keep the '?' placeholder.
			drawCSDBitmapGlyph(buf, stride, cx, yOff, h, '?', c)
		}
		cx += it.adv
	}
}

// isCSDBitmapRune reports whether r is drawn by the embedded bitmap font:
// printable ASCII, plus en/em dash mapped to '-'.
func isCSDBitmapRune(r rune) bool {
	return r >= 32 && r <= 126 || r == '–' || r == '—'
}

// drawCSDBitmapGlyph paints one embedded bitmap glyph at (x, yOff).
func drawCSDBitmapGlyph(buf []byte, stride, x, yOff, h int, ch byte, c [4]byte) {
	g := csdFont[ch-32]
	for row := 0; row < csdBitmapGlyphH; row++ {
		bits := g[row]
		py := yOff + row
		if py >= h {
			break
		}
		for col := 0; col < 6; col++ {
			if bits&(0x80>>uint(col)) != 0 {
				putPx(buf, stride, x+col, py, c[2], c[1], c[0])
			}
		}
	}
}

